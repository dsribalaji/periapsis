/**
 * Regenerates `src/core/ephemeris/smallBodies.data.ts` from NASA/JPL's Small-Body Database.
 *
 * Run by a maintainer, never by the app: the output is committed, so the app stays offline at
 * runtime and the same build always draws the same sky. Only public object designations are
 * sent to the API.
 *
 * Elements are osculating heliocentric ecliptic J2000 elements at the solution's own epoch
 * (`epoch_jd_tdb`). The app propagates them as a two-body Kepler orbit, which is exact at the
 * epoch and drifts with time from it - by roughly arcminutes per decade for a main-belt
 * asteroid, far more for a comet that passes Jupiter. The epoch ships with the data so the UI
 * can say how old it is.
 *
 * Usage: node scripts/fetch-small-bodies.mjs
 */
import { writeFileSync } from 'node:fs';

/** [designation sent to SBDB, id used in the app, display name, kind]. */
const CATALOGUE = [
  ['1', 'ceres', 'Ceres', 'dwarf'],
  ['134340', 'pluto', 'Pluto', 'dwarf'],
  ['136199', 'eris', 'Eris', 'dwarf'],
  ['136108', 'haumea', 'Haumea', 'dwarf'],
  ['136472', 'makemake', 'Makemake', 'dwarf'],
  ['2', 'pallas', 'Pallas', 'asteroid'],
  ['4', 'vesta', 'Vesta', 'asteroid'],
  ['10', 'hygiea', 'Hygiea', 'asteroid'],
  ['16', 'psyche', 'Psyche', 'asteroid'],
  ['433', 'eros', 'Eros', 'asteroid'],
  ['25143', 'itokawa', 'Itokawa', 'asteroid'],
  ['101955', 'bennu', 'Bennu', 'asteroid'],
  ['162173', 'ryugu', 'Ryugu', 'asteroid'],
  ['99942', 'apophis', 'Apophis', 'asteroid'],
  ['3200', 'phaethon', 'Phaethon', 'asteroid'],
  ['1P', 'halley', '1P/Halley', 'comet'],
  ['2P', 'encke', '2P/Encke', 'comet'],
  ['67P', 'churyumov', '67P/Churyumov-Gerasimenko', 'comet'],
  ['9P', 'tempel1', '9P/Tempel 1', 'comet'],
];

const num = (elements, name) => {
  const e = elements.find((x) => x.name === name);
  if (!e) throw new Error(`missing element ${name}`);
  const v = Number(e.value);
  if (!Number.isFinite(v)) throw new Error(`non-numeric element ${name}: ${e.value}`);
  return v;
};

const rows = [];
for (const [sstr, id, name, kind] of CATALOGUE) {
  const url = `https://ssd-api.jpl.nasa.gov/sbdb.api?sstr=${encodeURIComponent(sstr)}&full-prec=true&phys-par=true`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${sstr}: HTTP ${res.status}`);
  const data = await res.json();
  const el = data.orbit.elements;
  const diameter = (data.phys_par ?? []).find((p) => p.name === 'diameter');
  const row = {
    id,
    name,
    kind,
    designation: data.object.fullname.trim(),
    epochJdTdb: Number(data.orbit.epoch),
    a: num(el, 'a'),
    e: num(el, 'e'),
    i: num(el, 'i'),
    node: num(el, 'om'),
    argPeri: num(el, 'w'),
    meanAnomaly: num(el, 'ma'),
    meanMotion: num(el, 'n'),
    diameterKm: diameter ? Number(diameter.value) : null,
  };
  if (!(row.e < 1)) throw new Error(`${sstr}: not an elliptic orbit (e = ${row.e})`);
  rows.push(row);
  console.log(`${row.designation.padEnd(40)} a=${row.a.toFixed(3)} e=${row.e.toFixed(4)}`);
  // Be polite to a public API.
  await new Promise((r) => setTimeout(r, 300));
}

const fetchedOn = new Date().toISOString().slice(0, 10);
const body = `/**
 * GENERATED by scripts/fetch-small-bodies.mjs on ${fetchedOn}. Do not edit by hand.
 *
 * Source: NASA/JPL Small-Body Database (SBDB) API, https://ssd-api.jpl.nasa.gov/sbdb.api
 * Osculating heliocentric elements, ecliptic and equinox J2000, at each solution's epoch (TDB).
 * Angles in degrees, a in AU, mean motion in degrees per day, diameter in km (null if unknown).
 */

import type { SmallBodyRecord } from './smallBodies.js';

export const SMALL_BODY_DATA: readonly SmallBodyRecord[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync('src/core/ephemeris/smallBodies.data.ts', body);
console.log(`wrote ${rows.length} bodies`);
